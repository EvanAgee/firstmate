#!/usr/bin/env bash
# Watch one GitHub Actions run to completion through GraphQL and wake firstmate once.
# GitHub's REST actions API (gh run view, gh run list, gh run watch) can refuse
# with 403 for hours while GraphQL keeps answering, so this reads the run's
# check suite on its commit instead:
# repository.object(expression:<sha>).checkSuites{workflowRun{databaseId}}.
#
# Arming writes state/<id>.check.sh, a byte-static private shim whose only data
# are the validated arguments as quoted literals, and binds it with
# fm-check-register.sh. The shim execs this script's poll mode, so the watcher
# runs tracked logic. Arming refuses to replace any other check for the task,
# such as a PR merge poll, but re-arms over an earlier CI watch.
# Arming warns, and still arms, when the run is not yet visible on <sha>: a run
# that is not on that commit never completes there, so its watch stays silent.
#
# The poll is silent while the run is queued or in progress and on any read
# error. When the run's check suite completes it prints one line,
#   CI green - <run url>
#   CI red <conclusion>: <job> <conclusion>, ... - <run url>
# then removes its own check and trust record, so it wakes firstmate once.
#
# --dispatch <branch> first runs `gh workflow run ci.yml --ref <branch>` and
# arms the run whose URL gh prints; <sha> must be that branch's head commit.
# It refuses when gh prints no run URL.
#
# Usage:
#   fm-ci-watch.sh <task-id> <owner/repo> <sha> <run-id>
#   fm-ci-watch.sh --dispatch <branch> <task-id> <owner/repo> <sha>
set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
FM_HOME="${FM_HOME:-$FM_ROOT}"
STATE="${FM_STATE_OVERRIDE:-$FM_HOME/state}"

# shellcheck source=bin/fm-pr-lib.sh
. "$SCRIPT_DIR/fm-pr-lib.sh"

# GitHub Actions' app id on github.com; filtering on it keeps other apps'
# check suites from crowding the run out of the first page.
ACTIONS_APP_ID=15368
SHIM_HEADER='# Generated by fm-ci-watch.sh: GraphQL CI watch.'

help() {
  sed -n '2,/^set -u/p' "$0" | sed '$d; s/^# \{0,1\}//'
}

usage() {
  help >&2
  exit 2
}

args_valid() {  # <task-id> <owner/repo> <sha> <run-id>
  fm_pr_task_id_valid "$1" \
    && [[ "$2" =~ ^[A-Za-z0-9-]+/[A-Za-z0-9._-]+$ ]] \
    && [[ "$3" =~ ^[0-9a-f]{40}$ ]] \
    && [[ "$4" =~ ^[1-9][0-9]*$ ]]
}

shim_content() {  # <state> <task-id> <owner/repo> <sha> <run-id>
  local cmd
  cmd=$(printf '%q ' "$SCRIPT_DIR/fm-ci-watch.sh" --poll "$@")
  printf '%s\n' '#!/usr/bin/env bash' "$SHIM_HEADER" "exec ${cmd% }"
}

# Print pending, green, or red plus the failing jobs; print nothing when the
# run is not on the commit or the read fails.
run_state() {  # <owner/repo> <sha> <run-id>
  # shellcheck disable=SC2016 # $owner, $name, $sha, and $app are GraphQL variables.
  gh api graphql -f owner="${1%%/*}" -f name="${1#*/}" -f sha="$2" \
    -F app="$ACTIONS_APP_ID" -f query='
query($owner:String!,$name:String!,$sha:String!,$app:Int!){
  repository(owner:$owner,name:$name){
    object(expression:$sha){
      ... on Commit{
        checkSuites(first:100,filterBy:{appId:$app}){
          nodes{status conclusion workflowRun{databaseId} checkRuns(first:100){nodes{name status conclusion}}}
        }
      }
    }
  }
}' --jq '[.data.repository.object.checkSuites.nodes[]? | select(.workflowRun.databaseId == '"$3"')]
  | first // empty
  | if .status != "COMPLETED" then "pending"
    elif .conclusion == "SUCCESS" then "green"
    else "red " + ((.conclusion // "unknown") | ascii_downcase)
      + ([.checkRuns.nodes[]?
          | select(.conclusion != "SUCCESS" and .conclusion != "SKIPPED" and .conclusion != "NEUTRAL")
          | .name + " " + ((.conclusion // .status) | ascii_downcase)]
         | if length > 0 then ": " + join(", ") else "" end)
    end' 2>/dev/null
}

case "${1:-}" in
  -h|--help) help; exit 0 ;;
esac

if [ "${1:-}" = --poll ]; then
  [ "$#" -eq 6 ] && args_valid "$3" "$4" "$5" "$6" || exit 0
  state=$2 id=$3 repo=$4 sha=$5 run=$6
  result=$(run_state "$repo" "$sha" "$run") || exit 0
  case "$result" in
    green|red*) ;;
    *) exit 0 ;;
  esac
  printf 'CI %s - https://github.com/%s/actions/runs/%s\n' "$result" "$repo" "$run"
  # Retire only this exact watch; a check re-armed since the watcher's
  # snapshot belongs to someone else.
  if cmp -s "$state/$id.check.sh" <(shim_content "$state" "$id" "$repo" "$sha" "$run"); then
    rm -f -- "$state/$id.check.sh" "$state/$id.check-trust"
  fi
  exit 0
fi

BRANCH=
if [ "${1:-}" = --dispatch ]; then
  [ "$#" -eq 5 ] || usage
  BRANCH=$2
  shift 2
  [[ "$BRANCH" =~ ^[A-Za-z0-9._/][A-Za-z0-9._/-]*$ ]] || usage
  set -- "$@" 1
fi
[ "$#" -eq 4 ] || usage
args_valid "$@" || usage
ID=$1 REPO=$2 SHA=$3 RUN=$4
CHECK="$STATE/$ID.check.sh"

[ -d "$STATE" ] && [ ! -L "$STATE" ] || { echo "error: state directory is unavailable" >&2; exit 1; }
if { [ -e "$CHECK" ] || [ -L "$CHECK" ]; } \
  && [ "$(sed -n 2p "$CHECK" 2>/dev/null)" != "$SHIM_HEADER" ]; then
  echo "error: state/$ID.check.sh already holds another check; refusing to replace it" >&2
  exit 1
fi

if [ -n "$BRANCH" ]; then
  out=$(gh workflow run ci.yml --ref "$BRANCH" -R "$REPO" 2>&1) \
    || { printf 'error: dispatch failed: %s\n' "$out" >&2; exit 1; }
  RUN=$(printf '%s\n' "$out" | grep -oE "/$REPO/actions/runs/[0-9]+" | head -1)
  RUN=${RUN##*/}
  [ -n "$RUN" ] || { printf 'error: gh printed no run URL after dispatch: %s\n' "$out" >&2; exit 1; }
fi

umask 077
TMP=$(mktemp "$STATE/.fm-ci-watch.XXXXXX") || exit 1
trap '[ -z "$TMP" ] || rm -f -- "$TMP"' EXIT HUP INT TERM
shim_content "$STATE" "$ID" "$REPO" "$SHA" "$RUN" > "$TMP" && chmod 0700 "$TMP" && mv -f -- "$TMP" "$CHECK" || exit 1
TMP=
if ! FM_HOME="$FM_HOME" FM_STATE_OVERRIDE="$STATE" "$SCRIPT_DIR/fm-check-register.sh" "$ID" >/dev/null; then
  rm -f -- "$CHECK"
  exit 1
fi
[ -n "$(run_state "$REPO" "$SHA" "$RUN")" ] \
  || echo "warning: run $RUN is not visible on ${SHA:0:12} yet; the watch stays silent until it is" >&2
printf 'armed: state/%s.check.sh watching https://github.com/%s/actions/runs/%s\n' "$ID" "$REPO" "$RUN"
